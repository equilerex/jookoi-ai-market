"""Condense a manual's command reference into one compact signature index (grep-only reference file).

Input: an extract folder from extract_manual.py, one file per command, numbered.
The regexes match a reference style of `ARG /TYPES` headings followed by value lines.
Adapt ARG_RE, VALUE_RE and the header text to the target manual's layout before use.
Output: one line per argument: `ARG /types = value|value|... : first sentence of meaning`.

Usage: python -I scripts/build_command_index.py <extract-dir> <out.md> <first-file-number> <last-file-number>
"""
import glob
import os
import re
import sys

ARG_RE = re.compile(r"^([A-Z][A-Z0-9_]*) (/[A-Z/]+)\s*$")
VALUE_RE = re.compile(r"^(\(no value\)|<[^>]{1,40}>|[a-z0-9_\-.,=*#:+]{1,30}|[a-z0-9_\-]+,<[^>]+>)$")


def first_sentence(text, limit=140):
    text = re.sub(r"\s+", " ", text).strip()
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    sentence = match.group(1) if match else text
    return sentence if len(sentence) <= limit else sentence[: limit - 1].rstrip() + "…"


def parse_command(path):
    lines = open(path, encoding="utf-8").read().splitlines()
    name = lines[0].lstrip("# ").strip()
    intro, args, current = [], [], None
    for index, line in enumerate(lines[2:], start=2):
        stripped = line.strip()
        arg = ARG_RE.match(stripped)
        # Default arguments (e.g. Toolbar NAME) have no type suffix: a bare caps word followed by a value line.
        bare = re.match(r"^([A-Z][A-Z0-9_]{2,})$", stripped)
        next_line = next((l.strip() for l in lines[index + 1:] if l.strip()), "")
        if bare and VALUE_RE.match(next_line):
            arg = bare
        if arg:
            types = arg.group(2) if arg.lastindex and arg.lastindex >= 2 else "(default arg)"
            current = {"name": arg.group(1), "types": types, "values": [], "meaning": []}
            args.append(current)
            continue
        if current is None:
            if stripped and not stripped.startswith("#") and stripped not in ("Command Arguments:", "Possible values", "Description"):
                intro.append(stripped)
            continue
        if not stripped or stripped.startswith("Example:"):
            continue
        if VALUE_RE.match(stripped) and (not lines[index - 1].strip() or lines[index - 1].strip().startswith("Example:") or not current["values"]):
            current["values"].append(stripped)
        elif not current["meaning"] or len(" ".join(current["meaning"])) < 200:
            current["meaning"].append(stripped)
    return name, first_sentence(" ".join(intro), 220), args


def main(extract_dir, out_path, first_file, last_file):
    out = ["# Internal command index", "",
           "Generated by `build_command_index.py` from the manual extract. One line per argument.",
           "Types: /S switch, /K keyword (ARG=value), /O optional value, /N numeric, /M multiple, /F file or folder name, /R raw (rest of line).",
           ""]
    for path in sorted(glob.glob(os.path.join(extract_dir, "*.txt"))):
        number = int(os.path.basename(path)[:4])
        if not first_file <= number <= last_file:
            continue
        name, intro, args = parse_command(path)
        out.append(f"## {name}")
        if intro:
            out.append(intro)
        for arg in args:
            named_values = [v for v in arg["values"] if v != "(no value)"]
            signature = f"{arg['name']} {arg['types']}" + (f" = {'|'.join(named_values)}" if named_values else "")
            meaning = first_sentence(" ".join(arg["meaning"]))
            # The manual describes each value separately; the captured sentence belongs to the first one.
            if len(named_values) > 1 and not named_values[0].startswith("<"):
                meaning = f"({named_values[0]}) {meaning}"
            out.append(f"- `{signature}`: {meaning}")
        out.append("")
    with open(out_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(out))
    print(f"{out_path}: {sum(len(l) for l in out)} chars")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4]))
